/**
 * ch09_ex02.c —— printf 的宽度、精度与标志（flag）：把数字排整齐
 */
#include <stdio.h>

int main(void)
{
                /**
         * 1) 宽度（width）：不足补空格，超过就原样输出，不会截断
         */
    printf("默认   : [%d]\n", 42);
    printf("宽 8   : [%8d]\n", 42);
    printf("左对齐 : [%-8d]\n", 42);
    printf("补零   : [%08d]\n", 42);
    printf("负数补零: [%08d] （负号占一格，这是对的）\n", -42);
    printf("超宽不截断: [%3d]\n", 123456);

                /**
         * 2) 精度（precision）：整数的"最少位数"，浮点的"小数位数"，字符串的"最多字符数"。
         */
    printf("整数  (%%.5d)  : [%.5d]\n", 42);
    printf("浮点  (%%.3f)  : [%.3f]\n", 3.14159265);
    printf("浮点  (%%.0f)  : [%.0f] （会四舍五入）\n", 3.7);
    printf("字符串(%%.3s)  : [%.3s]\n", "abcdefg");
    printf("宽度+精度(%%.3f): [%10.3f]\n", 3.14159);

                /* 3) 标志：+ 总是带符号，空格 正数留空位， # 加前缀 */
    printf("带符号  : [%+d] [%+d]\n", 42, -42);
    printf("空格标志: [% d] [% d]\n", 42, -42);
    printf("井号十六: [%#x] [%#X] [%#o]\n", 255, 255, 64);

                /* 变式：宽度 / 精度都可以是 *，由参数在运行时决定 —— 这时 * 自己也要占一个参数 */
    int w = 10;
    printf("运行时宽度 %d : [%*d]\n", w, w, 7);
    printf("运行时精度 %d : [%.*f]\n", 2, 2, 3.14159);

                /* 4) 典型用途：把传感器数据排成表格，列才对得齐 */
    static const int raw[4] = { 12, 345, -6, 7890 };
    printf("\n 序号 |  原始值 |   换算值\n");
    printf("------+---------+----------\n");
    for (int k = 0; k < 4; k++) {
        printf(" %4d | %7d | %9.3f\n", k, raw[k], raw[k] * 0.061);
    }
    return 0;
}
