/**
 * ch08_ex05.c —— 【参数括号铁律】之二：每个参数出现的地方都要加括号
 */
#include <stdio.h>

#define SQ_BAD(x)  (x * x)          /**
 * 错：参数 x 没有单独加括号
 */
#define SQ_OK(x)   ((x) * (x))      /**
 * 对：体加括号 + 每个参数加括号
 */

#define MIN_BAD(a, b) (a) < (b) ? (a) : (b)     /**
 * 错：三元表达式整体没加括号
 */
#define MIN_OK(a, b)  (((a) < (b)) ? (a) : (b)) /**
 * 对
 */

int main(void)
{
                /**
         * 1) 参数是"表达式"时，不加括号会被优先级拆散
         */
    printf("SQ_BAD(1 + 2) = %d   <-- 展开成 (1 + 2 * 1 + 2) = 5\n", SQ_BAD(1 + 2));
    printf("SQ_OK (1 + 2) = %d   <-- 展开成 ((1 + 2) * (1 + 2)) = 9\n", SQ_OK(1 + 2));

                /* 2) 参数是单个变量时两种写法完全一样 —— 这就是"平时看不出错"的原因 */
    int v = 5;
    printf("参数是单个变量时两者相同 : SQ_BAD(v) = %d , SQ_OK(v) = %d\n",
           SQ_BAD(v), SQ_OK(v));

                /* 3) 三元宏的括号坑：2 * MIN_BAD(3, 4) 展开成 2 * (3) < (4) ? (3) : (4) */
    printf("2 * MIN_BAD(3, 4) = %d   <-- 展开后先算 6 < 4，得到 4\n", 2 * MIN_BAD(3, 4));
    printf("2 * MIN_OK (3, 4) = %d   <-- 正确\n", 2 * MIN_OK(3, 4));

        /* 4) 优先级更低的运算符（赋值）藏在参数里时，翻车更隐蔽： SQ_BAD(a = 1 + 2) 展开成 (a = 1 + 2 * a = 1 + 2)，根本编译不过； 而 SQ_OK 因为加了括号，反而能正常工作 —— 括号也是一种"防呆" */
    int a = 1, b = 2;
    printf("SQ_OK(a = 7) = %d , 之后 a = %d\n", SQ_OK(a = 7), a);
    printf("对照：SQ_BAD 遇到赋值会直接编译报错（见章末\"实测报错\"）\n");
    printf("b 没参与运算，仍然等于 %d\n", b);
    return 0;
}
